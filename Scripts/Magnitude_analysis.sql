--Find total customers by countries

select DISTINCT country,COUNT(country) Total_num 
from gold_dim_customers gdc 
GROUP BY country 
ORDER BY Total_num DESC

--Find total customers by gender
select DISTINCT gender,COUNT(gender) Total_num 
from gold_dim_customers gdc 
GROUP BY gender 
ORDER BY Total_num DESC

--Find total products by category

select DISTINCT category,COUNT(category) Total_cat 
from gold_dim_products gdp 
GROUP BY category ORDER BY 
Total_cat DESC 

--What is the average costs in each category

select DISTINCT category,AVG(cost) AVG_Total 
from gold_dim_products gdp 
GROUP BY category 
ORDER BY AVG_Total DESC

--What is the total revenu generated for each category

select gdp.category, SUM(gfs.sales_amount) total_revenu 
from gold_fact_sales gfs 
LEFT JOIN gold_dim_products gdp 
ON gfs.product_key =gdp.product_key 
GROUP BY gdp.category
ORDER BY total_revenu DESC

--Find total revenu is generated by each customer

select gdc.customer_key,SUM(gfs.sales_amount ) Total_revenu 
from gold_fact_sales gfs
LEFT JOIN gold_dim_customers gdc  
ON gdc.customer_key =gfs.customer_key 
GROUP BY gdc.customer_key
ORDER BY  Total_revenu DESC

--What is the distribution of solid items across countries

SELECT  country,SUM(gfs.quantity ) Num_quantity from gold_fact_sales gfs 
LEFT JOIN gold_dim_customers gdc 
ON gfs.customer_key=gdc.customer_key
GROUP BY country
ORDER BY Num_quantity DESC










